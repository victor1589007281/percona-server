-- ============================================================================
-- Test 23: Complex Queries
-- ============================================================================

-- Subquery
SELECT * FROM test_table WHERE value > (SELECT AVG(value) FROM test_table);

-- UNION
SELECT 'Table1' AS source, id, name FROM test_table WHERE id < 5
UNION ALL
SELECT 'Table1_High' AS source, id, name FROM test_table WHERE id >= 5;

-- Common Table Expression (CTE)
WITH cte AS (
    SELECT id, name, value,
           ROW_NUMBER() OVER (ORDER BY value DESC) AS rn
    FROM test_table
)
SELECT * FROM cte WHERE rn <= 3;

-- Window function
SELECT 
    id, name, value,
    AVG(value) OVER (ORDER BY id ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS moving_avg
FROM test_table;

