-- ============================================================================
-- Test 10: COM_STMT_PREPARE (0x16) - Prepared Statements
-- ============================================================================
-- Binary protocol - requires C API or connector that supports it

-- Via mysql client (limited support):
PREPARE stmt1 FROM 'SELECT * FROM test_table WHERE id = ?';
SET @id = 1;
EXECUTE stmt1 USING @id;
DEALLOCATE PREPARE stmt1;

-- More complex prepared statement
PREPARE stmt2 FROM 'INSERT INTO test_table (name, value) VALUES (?, ?)';
SET @name = 'prepared_test';
SET @value = 999;
EXECUTE stmt2 USING @name, @value;
DEALLOCATE PREPARE stmt2;

-- Prepared statement with multiple parameters
PREPARE stmt3 FROM 'UPDATE test_table SET value = ? WHERE name = ? AND value > ?';
SET @new_value = 1500;
SET @name_filter = 'test1';
SET @min_value = 0;
EXECUTE stmt3 USING @new_value, @name_filter, @min_value;
DEALLOCATE PREPARE stmt3;

