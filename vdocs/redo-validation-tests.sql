-- Test 23: Trigger Checkpoint
-- ============================================================================
-- Force a checkpoint to see checkpoint-related records

-- Generate significant redo log activity
CREATE PROCEDURE generate_redo_load()
BEGIN
    DECLARE i INT DEFAULT 0;
    WHILE i < 100 DO
        INSERT INTO test_rec_insert VALUES (1000 + i, CONCAT('User', i), i * 10.5);
        SET i = i + 1;
    END WHILE;
END;

CALL generate_redo_load();
DROP PROCEDURE generate_redo_load;

