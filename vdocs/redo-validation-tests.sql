-- Test 20: Complex Multi-Table Transactions
-- ============================================================================

CREATE TABLE test_orders (
    order_id INT PRIMARY KEY AUTO_INCREMENT,
    customer VARCHAR(100),
    total DECIMAL(10,2)
) ENGINE=InnoDB;

CREATE TABLE test_order_items (
    item_id INT PRIMARY KEY AUTO_INCREMENT,
